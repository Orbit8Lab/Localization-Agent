def normalize_error_types(values: Optional[Iterable[str]]) -> str:
    """Render predicted error types as one cell, validating the vocabulary.

    An unrecognized label is a bug in the caller, not a tester problem, so
    it fails loudly here rather than shipping a value no downstream reader
    can aggregate. Accepts internal bug_report tokens ("placeholder") as
    well as kit labels ("Tag/Markup") so callers can pass findings through
    untranslated. Order is preserved, duplicates dropped."""
    if not values:
        return ""
    out: List[str] = []
    for raw in values:
        value = str(raw).strip()
        if not value:
            continue
        label = TEST_ERROR_TYPE_BY_TOKEN.get(value.lower(), value)
        if label not in TEST_ERROR_TYPES:
            raise ValueError(
                f"unknown predicted error type {raw!r}; expected one of "
                f"{TEST_ERROR_TYPES} (or a bug_report token)")
        if label not in out:
            out.append(label)
    return ERROR_TYPE_SEP.join(out)


def emit_test_kit(path: Path, rows: List[Dict[str, str]], *,
                  extra_columns: Sequence[str] = (),
                  risk_first: bool = True) -> int:
    """Write the test kit workbook (§4.5).

    ``rows`` carry the agent-authored columns; TEST_* values are ignored —
    they belong to the tester. ``AI_ErrorTypes`` accepts either a
    pre-joined string or a list of labels/tokens. ``extra_columns`` appends
    agent-authored context AFTER the standard block, so the standard shape
    is extended, never altered. With ``risk_first`` the predicted-bug rows
    sort to the top (stable within each group). Returns the row count."""
    import openpyxl
    from openpyxl.styles import Alignment, Font, PatternFill
    from openpyxl.worksheet.datavalidation import DataValidation

    headers = list(TEST_KIT_FORM_HEADERS)
    for column in extra_columns:
        if column in headers:
            raise ValueError(f"extra column {column!r} collides with the "
                             f"standard test kit form")
        headers.append(column)

    ordered = list(rows)
    if risk_first:
        # Stable: preserves the caller's ordering (usually corpus order)
        # inside the Yes block and inside the No block.
        ordered.sort(key=lambda r: 0 if _is_expected_bug(r) else 1)

    book = openpyxl.Workbook()
    sheet = book.active
    sheet.title = "Test Kit"
    sheet.append(headers)
    for cell in sheet[1]:
        name = str(cell.value)
        fill = (_HEADER_TEST if name in TEST_FILLED_COLUMNS
                else _HEADER_AI if name.startswith("AI_") else _HEADER_AGENT)
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = PatternFill("solid", start_color=fill)
        cell.alignment = Alignment(vertical="center", wrap_text=True)

    for row in ordered:
        values = []
        for header in headers:
            if header in TEST_FILLED_COLUMNS:
                values.append("")            # the tester's column
            elif header == "AI_ErrorTypes":
                raw = row.get(header, "")
                values.append(raw if isinstance(raw, str)
                              else normalize_error_types(raw))
            else:
                values.append(row.get(header, ""))
        sheet.append(values)
        if _is_expected_bug(row):
            sheet.cell(row=sheet.max_row, column=1).fill = PatternFill(
                "solid", start_color=_RISK_FILL)

    last = max(len(ordered), 1) + 1
    for col, options in FORM_DROPDOWNS["testkit"].items():
        if col not in headers:
            continue
        validation = DataValidation(
            type="list", formula1='"' + ",".join(options) + '"',
            allow_blank=True, showDropDown=False)
        sheet.add_data_validation(validation)
        letter = sheet.cell(row=1, column=headers.index(col) + 1).column_letter
        validation.add(f"{letter}2:{letter}{last}")

    widths = {"StringID": 34, "StringType": 12, "StringLocation": 30,
              "Source": 45, "Target_Current": 45,
              "AI_ExpectedBug": 14, "AI_ErrorTypes": 28,
              "TEST_Reproduction": 40, "TEST_Context": 26,
              "TEST_AssignedTeam": 18, "TEST_Decision": 26,
              "TEST_Suggestion": 40, "TEST_Notes": 36}
    for name, width in widths.items():
        if name in headers:
            letter = sheet.cell(
                row=1, column=headers.index(name) + 1).column_letter
            sheet.column_dimensions[letter].width = width
    sheet.freeze_panes = "F2"                # keep the string visible while
                                             # filling the TEST_* columns
    sheet.auto_filter.ref = f"A1:{sheet.cell(row=1, column=len(headers)).column_letter}{last}"

    guide = book.create_sheet("说明 How to fill")
    for line in _GUIDE:
        guide.append([line])
    guide.column_dimensions["A"].width = 100
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    book.save(path)
    return len(ordered)


def _is_expected_bug(row: Dict[str, str]) -> bool:
    return str(row.get("AI_ExpectedBug", "")).strip().lower() == "yes"
