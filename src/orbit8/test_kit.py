    "Fill ONLY the TEST_* columns (green headers). Every other column is "
    "generated by the LQA team and must come back unchanged — we match your "
    "results back by StringID.",
    "",
    "WHAT THE COLUMNS MEAN",
    "  StringID / StringType / StringLocation — where the string lives in "
    "the build. Use these to find it in game.",
    "  Source / Target_Current — the original text and what is currently "
    "shown in the localized build.",
    "  AI_ExpectedBug — our prediction that this string needs extra "
    "attention. A HINT, NOT A VERDICT.",
    "  AI_ErrorTypes — what we predict could go wrong here "
    "(multiple values separated by '; ').",
    "",
    "IMPORTANT: AI_ExpectedBug = No does NOT mean the string is fine. "
    "If you see a problem on a 'No' row, report it — those are the most "
    "valuable finds, because our prediction missed them.",
    "",
    "HOW TO FILL",
    "  TEST_Decision (dropdown) — REQUIRED for every row you test:",
    "    No Issue                  — you checked it in game; it displays "
